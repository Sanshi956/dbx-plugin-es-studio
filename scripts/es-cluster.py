#!/usr/bin/env python3
"""Low-footprint REAL Elasticsearch cluster for ES Studio integration tests.

Spec: docs/00-SPEC.md section 9 (resource safety).
This is a real ES instance, not a mock. It exists to satisfy requirement 13.2
(real-cluster integration tests) without risking the host machine:

  * 512 MB heap, no MaxMetaspaceSize cap (ES 8.19 loads ~40 modules), single-node, loopback only
  * independent config dir; the installed ES distribution is NEVER modified
  * data / logs / tmp all under D: (C: is low on space)
  * refuses to start unless >= 3 GB RAM is available
  * built-in guard: kills the whole process tree if available RAM drops < 1 GB

IMPORTANT (Windows / agent shells): `start` is a LONG-RUNNING FOREGROUND process.
It must be launched as a background task, because a detached child java process
gets reclaimed when the parent shell exits. The start process owns the ES JVM and
stays alive until `stop`, a guard trip, or the JVM exiting.

Usage:
  python scripts/es-cluster.py start     # run as a BACKGROUND TASK, prints READY when healthy
  python scripts/es-cluster.py status    # one-shot health + free RAM
  python scripts/es-cluster.py stop      # deterministic teardown

Overrides (for reproducing on another machine):
  ES_HOME, ES_STUDIO_TEST_ROOT, ES_STUDIO_TEST_PORT,
  ES_STUDIO_MIN_FREE_GB, ES_STUDIO_GUARD_FLOOR_GB
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

import psutil

ES_HOME = Path(os.environ.get(
    "ES_HOME",
    r"D:/software/dev/elasticsearch-8.19.23-windows-x86_64/elasticsearch-8.19.23",
))
ROOT = Path(os.environ.get("ES_STUDIO_TEST_ROOT", r"D:/tmp/es-studio"))
PORT = int(os.environ.get("ES_STUDIO_TEST_PORT", "19200"))
MIN_FREE_GB = float(os.environ.get("ES_STUDIO_MIN_FREE_GB", "3"))
GUARD_FLOOR_GB = float(os.environ.get("ES_STUDIO_GUARD_FLOOR_GB", "1"))
BASE = f"http://127.0.0.1:{PORT}"
MARKER = ROOT / "cluster.json"

YML = """# Generated by scripts/es-cluster.py - integration test cluster only.
cluster.name: es-studio-test
node.name: es-studio-node-1
discovery.type: single-node
network.host: 127.0.0.1
http.port: {port}
path.data: {data}
path.logs: {logs}
# Snapshot repositories (P3 Snapshots page) must live under an allowed path.
path.repo: ["{repo}"]
xpack.security.enabled: false
xpack.security.enrollment.enabled: false
xpack.ml.enabled: false
xpack.watcher.enabled: false
ingest.geoip.downloader.enabled: false
cluster.routing.allocation.disk.threshold_enabled: false
action.destructive_requires_name: false
"""

# NOTE: never cap MaxMetaspaceSize here. ES 8.19 loads ~40 modules (APM, OTel,
# profiling, ESQL, ...) and a 128m cap reliably causes a metaspace OOM during
# bootstrap; the JVM then exits via -XX:+ExitOnOutOfMemoryError after dumping heap.
JVM_OPTIONS = """# Generated by scripts/es-cluster.py - keep the heap tiny on a 16 GB workstation.
-Xms512m
-Xmx512m
-XX:MaxDirectMemorySize=256m
"""


def free_gb() -> float:
    return psutil.virtual_memory().available / (2 ** 30)


def prepare_config() -> Path:
    cfg = ROOT / "config"
    if not cfg.exists():
        shutil.copytree(ES_HOME / "config", cfg)
    (cfg / "jvm.options.d").mkdir(parents=True, exist_ok=True)
    (cfg / "jvm.options.d" / "es-studio.options").write_text(JVM_OPTIONS, encoding="utf-8")
    (cfg / "elasticsearch.yml").write_text(
        YML.format(
            port=PORT,
            data=(ROOT / "data").as_posix(),
            logs=(ROOT / "logs").as_posix(),
            repo=(ROOT / "snapshots").as_posix(),
        ),
        encoding="utf-8",
    )
    for name in ("data", "logs", "tmp", "snapshots"):
        (ROOT / name).mkdir(parents=True, exist_ok=True)
    return cfg


def probe():
    try:
        with urllib.request.urlopen(BASE + "/", timeout=3) as r:
            return r.status, json.loads(r.read().decode("utf-8"))
    except Exception as e:  # startup polling: any error means "not ready yet"
        return None, str(e)


def read_marker():
    if not MARKER.exists():
        return None
    try:
        return json.loads(MARKER.read_text(encoding="utf-8"))
    except Exception:
        return None


def cluster_pids():
    """Find the ES JVM strictly: java + ES bootstrap main class + our tmpdir path."""
    out = []
    for p in psutil.process_iter(["pid", "name", "cmdline"]):
        try:
            name = (p.info["name"] or "").lower()
            if not name.startswith("java"):
                continue
            cl = " ".join(p.info["cmdline"] or [])
            if "org.elasticsearch.bootstrap.Elasticsearch" in cl and "es-studio" in cl:
                out.append(p)
        except Exception:
            pass
    return out


def kill_all(root_pid=None):
    targets = []
    if root_pid is not None:
        try:
            parent = psutil.Process(root_pid)
            targets = [parent] + parent.children(recursive=True)
        except psutil.NoSuchProcess:
            pass
    known = {t.pid for t in targets}
    for p in cluster_pids():
        if p.pid not in known:
            targets.append(p)
            known.add(p.pid)
    for p in reversed(targets):
        try:
            p.kill()
            print("killed", p.pid, flush=True)
        except Exception:
            pass


def clean_stale():
    """Clear only OUR test dir after a crashed bootstrap; never touch anything else."""
    logs = ROOT / "logs"
    if logs.exists():
        for dump in logs.glob("*.hprof"):
            print(f"removing stale heap dump {dump.name} ({dump.stat().st_size / 2**20:.0f} MB)", flush=True)
            dump.unlink()
    data = ROOT / "data"
    # Only wipe when the previous bootstrap never got as far as writing cluster
    # state (`_state` is created by ES 8 on a completed startup). A healthy data
    # dir must survive restarts, otherwise every `start` loses the seeded data
    # and a bulk rmtree trips the delete guard for no reason.
    if data.exists() and any(data.iterdir()) and not (data / "_state").exists():
        shutil.rmtree(data)
        print("cleared incomplete data dir from crashed bootstrap", flush=True)
    data.mkdir(parents=True, exist_ok=True)


def cmd_start() -> int:
    """Long-running: owns the ES JVM and guards host memory. Run as a background task."""
    if not (ES_HOME / "bin" / "elasticsearch.bat").exists():
        print(f"ERROR: ES_HOME not found: {ES_HOME}", file=sys.stderr, flush=True)
        return 2
    avail = free_gb()
    if avail < MIN_FREE_GB:
        print(f"REFUSED: available {avail:.2f} GB < {MIN_FREE_GB} GB (avoid swapping/OOM)", flush=True)
        return 3
    status, _ = probe()
    if status == 200:
        print(f"already healthy at {BASE}", flush=True)
        return 0

    clean_stale()
    cfg = prepare_config()
    env = dict(os.environ)
    env["ES_PATH_CONF"] = str(cfg)
    env["ES_JAVA_HOME"] = str(ES_HOME / "jdk")
    env["ES_TMPDIR"] = str(ROOT / "tmp")
    env.pop("ES_JAVA_OPTS", None)

    comspec = os.environ.get("ComSpec", r"C:/Windows/System32/cmd.exe")
    launcher = str(ES_HOME / "bin" / "elasticsearch.bat")
    log = open(ROOT / "launch.log", "ab", buffering=0)
    proc = subprocess.Popen(
        [comspec, "/c", launcher],
        cwd=str(ES_HOME), env=env, stdin=subprocess.DEVNULL,
        stdout=log, stderr=subprocess.STDOUT,
    )
    MARKER.write_text(json.dumps({
        "pid": proc.pid, "port": PORT, "es_home": str(ES_HOME),
        "started": time.strftime("%Y-%m-%d %H:%M:%S"),
    }), encoding="utf-8")
    print(f"launched pid={proc.pid}, waiting for {BASE} ...", flush=True)

    ready = False
    deadline = time.time() + 240
    while time.time() < deadline:
        status, body = probe()
        if status == 200:
            v = (body or {}).get("version", {}).get("number", "?")
            print(f"READY: ES {v} at {BASE}; RAM available {free_gb():.2f} GB", flush=True)
            ready = True
            break
        if proc.poll() is not None:
            print("ERROR: launcher exited early; see " + str(ROOT / "launch.log"), flush=True)
            if MARKER.exists():
                MARKER.unlink()
            return 4
        time.sleep(3)
    if not ready:
        print("ERROR: timed out waiting for ES; see " + str(ROOT / "launch.log"), flush=True)
        kill_all(proc.pid)
        if MARKER.exists():
            MARKER.unlink()
        return 5

    try:
        while True:
            if proc.poll() is not None:
                print("ES JVM exited; start process stops", flush=True)
                break
            if not MARKER.exists():
                print("marker removed by stop; terminating ES", flush=True)
                kill_all(proc.pid)
                break
            avail = free_gb()
            if avail < GUARD_FLOOR_GB:
                report = ROOT / "guard-report.txt"
                report.write_text(
                    f"STOPPED BY GUARD at {time.strftime('%Y-%m-%d %H:%M:%S')}\n"
                    f"available RAM {avail:.2f} GB < floor {GUARD_FLOOR_GB} GB\n",
                    encoding="utf-8",
                )
                print(report.read_text(encoding="utf-8").strip(), flush=True)
                kill_all(proc.pid)
                break
            time.sleep(15)
    finally:
        if MARKER.exists():
            MARKER.unlink()
    return 0


def cmd_status() -> int:
    status, body = probe()
    print(f"marker={read_marker()}", flush=True)
    if status == 200:
        print(f"HEALTHY ES {body.get('version', {}).get('number')} cluster={body.get('cluster_name')}", flush=True)
        print(f"RAM available {free_gb():.2f} GB", flush=True)
        return 0
    print(f"NOT HEALTHY: {body}; RAM available {free_gb():.2f} GB", flush=True)
    return 1


def cmd_stop() -> int:
    m = read_marker()
    root = None
    if m:
        try:
            root = psutil.Process(m["pid"])
        except psutil.NoSuchProcess:
            pass
    kill_all(m["pid"] if m else None)
    if MARKER.exists():
        MARKER.unlink()
    print(f"stopped; RAM available {free_gb():.2f} GB", flush=True)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["start", "status", "stop"])
    a = ap.parse_args()
    return {"start": cmd_start, "status": cmd_status, "stop": cmd_stop}[a.action]()


if __name__ == "__main__":
    sys.exit(main())
